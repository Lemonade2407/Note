R = 14


def _node(f, x, y, key, bf=None):
    f.circle(x, y, R, fill="#fff")
    f.text(x, y, key, 14)
    if bf is not None:
        f.text(x + R + 10, y - R + 3, bf, 11)


def _rect(f, x, y, w, h, lab, hl=None):
    f.rect(x, y, w, h, fill="#fff")
    if lab:
        f.text(x + w / 2, y + h / 2 + 1, lab, 14)
    if hl:
        xa = x - 8
        f.line(xa, y, xa, y + h)
        f.line(xa - 4, y, xa + 4, y)
        f.line(xa - 4, y + h, xa + 4, y + h)
        f.text(xa - 7, y + h / 2, hl, 11, anchor="end")


def _panel(f, ox, nodes, rects, edges, labels, oy=0):
    nx = {k: (x + ox, y + oy, bf) for k, (x, y, bf) in nodes.items()}
    rx = {k: (x + ox, y + oy, w, h, hl) for k, (x, y, w, h, hl) in rects.items()}
    for lab, (x, y, w, h, hl) in rx.items():
        _rect(f, x, y, w, h, lab, hl)
    for key, (x, y, bf) in nx.items():
        _node(f, x, y, key, bf)

    def anchor(ref):
        if ref in nx:
            x, y, _ = nx[ref]
            return (x, y)
        x, y, w, h, _ = rx[ref]
        return (x + w / 2, y)

    for a, b in edges:
        p1, p2 = anchor(a), anchor(b)
        dx, dy = p2[0] - p1[0], p2[1] - p1[1]
        d = (dx * dx + dy * dy) ** 0.5 or 1
        ux, uy = dx / d, dy / d
        t1 = R + 1 if a in nx else 0
        t2 = R + 1 if b in nx else 0
        f.line(p1[0] + ux * t1, p1[1] + uy * t1, p2[0] - ux * t2, p2[1] - uy * t2)
    for text, x, y, size in labels:
        f.text(x + ox, y + oy, text, size, color="#333")


def _trans(f, x, y, lines):
    for i, s in enumerate(lines):
        f.text(x, y + i * 16, s, 11, color="#333")


