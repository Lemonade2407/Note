# ---------------------------------------------------------------- 辅助
def tl(f, cx, y, lines, size=TXT, dy=None, **kw):
    """以 (cx,y) 为第一行中心，向下逐行排列。"""
    dy = dy or size * 1.55
    for i, s in enumerate(lines):
        f.text(cx, y + i * dy, s, size=size, **kw)


def vc(f, cx, y0, s, size=TXT, dy=None):
    """竖排文字（每字一行，字正立）。"""
    dy = dy or size * 1.45
    for i, ch in enumerate(s):
        f.text(cx, y0 + i * dy, ch, size=size)


def oarrow(f, x, y1, y2, sh=5, hh=9, hl=14, sw=1.4):
    """竖直空心（双线杆）箭头，y1->y2。"""
    s = 1 if y2 > y1 else -1
    yb = y2 - s * hl
    f.poly([(x - sh, y1), (x - sh, yb), (x - hh, yb), (x, y2), (x + hh, yb),
            (x + sh, yb), (x + sh, y1), (x - sh, y1)], sw=sw)
    f.line(x - sh, y1, x + sh, y1, sw=sw)


def oarrowh(f, y, x1, x2, sh=5, hh=9, hl=14, sw=1.4):
    """水平空心（双线杆）箭头，x1->x2。"""
    s = 1 if x2 > x1 else -1
    xb = x2 - s * hl
    f.poly([(x1, y - sh), (xb, y - sh), (xb, y - hh), (x2, y), (xb, y + hh),
            (xb, y + sh), (x1, y + sh), (x1, y - sh)], sw=sw)
    f.line(x1, y - sh, x1, y + sh, sw=sw)


def odl(f, y, x1, x2, sh=4.5, hh=11, hl=15, sw=1.5):
    """双头空心箭头（水平）。"""
    xb1, xb2 = x1 + hl, x2 - hl
    f.poly([(x1, y), (xb1, y - hh), (xb1, y - sh), (xb2, y - sh), (xb2, y - hh),
            (x2, y), (xb2, y + hh), (xb2, y + sh), (xb1, y + sh), (xb1, y + hh),
            (x1, y)], sw=sw)


def odlv(f, x, y1, y2, sh=5, hh=9, hl=14, sw=1.4):
    """双头空心箭头（竖直）。"""
    yb1, yb2 = y1 + hl, y2 - hl
    f.poly([(x, y1), (x - hh, yb1), (x - sh, yb1), (x - sh, yb2), (x - hh, yb2),
            (x, y2), (x + hh, yb2), (x + sh, yb2), (x + sh, yb1), (x + hh, yb1),
            (x, y1)], sw=sw)


def dimh(f, y, x1, x2, hl=8):
    """尺寸线：两端竖向短线 + 双向箭头。"""
    f.line(x1, y - 10, x1, y + 10, sw=1.2)
    f.line(x2, y - 10, x2, y + 10, sw=1.2)
    f.arrow(x1 + 2, y, x2 - 2, y, sw=1.2, head=hl)
    f.arrow(x2 - 2, y, x1 + 2, y, sw=1.2, head=hl)


def dia(f, cx, cy, w, h, s, size=TXT, sw=1.5, lh=1.5):
    K.dia(f, cx, cy, w, h, None, sw=sw)
    if isinstance(s, str):
        s = [s]
    n = len(s)
    y0 = cy - (n - 1) * size * lh / 2
    for i, t in enumerate(s):
        f.text(cx, y0 + i * size * lh, t, size=size)


def circ(f, cx, cy, s, r=9, size=12):
    f.circle(cx, cy, r, fill=BOXW, sw=1.2)
    f.text(cx, cy, s, size=size)


def sub(f, cx, cy, base, sb, size=16, ss=11):
    """带下标的符号，如 G₂ / R₀。"""
    f.text(cx - ss * 0.45, cy, base, size=size)
    f.text(cx + size * 0.36, cy + size * 0.3, sb, size=ss)


def lbox(f, x, y, w, h, lines, size=16, pad=11, dy=None, sw=1.5):
    """左对齐多行文字的矩形框。"""
    f.rect(x, y, w, h, fill=BOXW, sw=sw)
    dy = dy or size * 1.45
    n = len(lines)
    y0 = y + h / 2 - (n - 1) * dy / 2
    for i, t in enumerate(lines):
        f.text(x + pad, y0 + i * dy, t, size=size, anchor="start")


def brace_h(f, x1, x2, y, h=9, tip=10, sw=1.3):
    """向下的大括号。"""
    m = (x1 + x2) / 2
    pts = [(x1, y), (x1 + 2, y + h * 0.6), (x1 + 8, y + h), (m - tip, y + h),
           (m - tip * 0.45, y + h + tip * 0.45), (m, y + h + tip),
           (m + tip * 0.45, y + h + tip * 0.45), (m + tip, y + h),
           (x2 - 8, y + h), (x2 - 2, y + h * 0.6), (x2, y)]
    f.poly(pts, sw=sw)


